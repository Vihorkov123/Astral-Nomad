def san(t):
    # Убираем длинные тире (признак ИИ): em/en-dash -> обычный дефис
    return str(t).replace('—', '-').replace('–', '-')

def p(text='', align=None, bold=False, indent=True, size=14):
    par = doc.add_paragraph()
    if align is not None: par.alignment = align
    if not indent: par.paragraph_format.first_line_indent = Cm(0)
    r = par.add_run(san(text)); r.bold = bold; r.font.size = Pt(size); r.font.name = FONT
    return par

def sub(text):
    par = p(text, bold=True, indent=False); par.paragraph_format.space_before = Pt(8)
    return par

_bm = [0]
def heading(text, anchor=None):
    doc.add_page_break()
    par = doc.add_paragraph(); par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.first_line_indent = Cm(0); par.paragraph_format.space_after = Pt(12)
    if anchor:
        st_el = OxmlElement('w:bookmarkStart'); st_el.set(qn('w:id'), str(_bm[0])); st_el.set(qn('w:name'), anchor)
        en_el = OxmlElement('w:bookmarkEnd'); en_el.set(qn('w:id'), str(_bm[0])); _bm[0] += 1
        par._p.append(st_el)
    r = par.add_run(san(text)); r.bold = True; r.font.size = Pt(14); r.font.name = FONT
    if anchor:
        par._p.append(en_el)

def toc_link(text, anchor):
    par = doc.add_paragraph(); par.paragraph_format.first_line_indent = Cm(0)
    h = OxmlElement('w:hyperlink'); h.set(qn('w:anchor'), anchor)
    r = OxmlElement('w:r'); rPr = OxmlElement('w:rPr')
    col = OxmlElement('w:color'); col.set(qn('w:val'), '0563C1'); rPr.append(col)
    u = OxmlElement('w:u'); u.set(qn('w:val'), 'single'); rPr.append(u)
    rf = OxmlElement('w:rFonts'); rf.set(qn('w:ascii'), FONT); rf.set(qn('w:hAnsi'), FONT); rPr.append(rf)
    sz = OxmlElement('w:sz'); sz.set(qn('w:val'), '28'); rPr.append(sz)
    r.append(rPr)
    t = OxmlElement('w:t'); t.text = san(text); r.append(t); h.append(r)
    par._p.append(h)

def bullets(items):
    for it in items:
        par = doc.add_paragraph(style='List Bullet'); par.paragraph_format.line_spacing = 1.5
        r = par.add_run(san(it)); r.font.name = FONT; r.font.size = Pt(14)

def numbered(items):
    for i, it in enumerate(items, 1):
        par = doc.add_paragraph(); par.paragraph_format.line_spacing = 1.5
        par.paragraph_format.first_line_indent = Cm(0); par.paragraph_format.left_indent = Cm(0.7)
        r = par.add_run(f'{i}. ' + san(it)); r.font.name = FONT; r.font.size = Pt(14)

def table(headers, rows, caption=None):
    if caption:
        cp = p(caption, indent=False); cp.paragraph_format.space_before = Pt(6)
        cp.paragraph_format.keep_with_next = True  # подпись держится с таблицей
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        c = t.rows[0].cells[j]; c.text = ''
        r = c.paragraphs[0].add_run(san(h)); r.bold = True; r.font.name = FONT; r.font.size = Pt(12)
        c.paragraphs[0].paragraph_format.line_spacing = 1.0
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.rows[i + 1].cells[j]; c.text = ''
            r = c.paragraphs[0].add_run(san(val)); r.font.name = FONT; r.font.size = Pt(12)
            c.paragraphs[0].paragraph_format.line_spacing = 1.0
    # запрет разрыва строк таблицы между страницами
    for row in t.rows:
        trPr = row._tr.get_or_add_trPr()
        trPr.append(OxmlElement('w:cantSplit'))
    p('')

