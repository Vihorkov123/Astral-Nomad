st.paragraph_format.space_after = Pt(0)
for sec in doc.sections:
    sec.left_margin = Cm(3); sec.right_margin = Cm(1.5)
    sec.top_margin = Cm(2); sec.bottom_margin = Cm(2)

def p(text='', align=None, bold=False, indent=True, size=14):
    par = doc.add_paragraph()
    if align is not None: par.alignment = align
    if not indent: par.paragraph_format.first_line_indent = Cm(0)
    r = par.add_run(text); r.bold = bold; r.font.size = Pt(size)
    r.font.name = 'Times New Roman'
    return par

def sub(text):
    par = p(text, bold=True, indent=False)
    par.paragraph_format.space_before = Pt(8)

def heading(text):
    doc.add_page_break()
    par = doc.add_paragraph(); par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.first_line_indent = Cm(0); par.paragraph_format.space_after = Pt(12)
    r = par.add_run(text); r.bold = True; r.font.size = Pt(14); r.font.name = 'Times New Roman'

def bullets(items):
    for it in items:
        par = doc.add_paragraph(style='List Bullet')
        par.paragraph_format.line_spacing = 1.5
        r = par.add_run(it); r.font.name = 'Times New Roman'; r.font.size = Pt(14)

def table(headers, rows, caption=None):
    if caption:
        cp = p(caption, indent=False); cp.paragraph_format.space_before = Pt(6)
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        c = t.rows[0].cells[j]; c.text = ''
        r = c.paragraphs[0].add_run(h); r.bold = True
        r.font.name = 'Times New Roman'; r.font.size = Pt(12)
        c.paragraphs[0].paragraph_format.line_spacing = 1.0
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.rows[i + 1].cells[j]; c.text = ''
            r = c.paragraphs[0].add_run(str(val))
            r.font.name = 'Times New Roman'; r.font.size = Pt(12)
            c.paragraphs[0].paragraph_format.line_spacing = 1.0
    p('')

