def make_audience_chart(path):
    W, H = 900, 460
    img = Image.new('RGB', (W, H), 'white'); d = ImageDraw.Draw(img)
    fp = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
    f = ImageFont.truetype(fp, 22); fb = ImageFont.truetype(fp, 26)
    parts = [('Игроки 12-25 (основная)', 68, (79, 130, 200)),
             ('Студенты IT и разработчики', 20, (255, 107, 94)),
             ('Прочие игроки платформы', 12, (120, 190, 120))]
    cx, cy, rad = 250, 250, 170
    start = -90
    for name, val, col in parts:
        ext = val / 100 * 360
        d.pieslice([cx-rad, cy-rad, cx+rad, cy+rad], start, start+ext, fill=col)
        start += ext
    d.text((cx-rad, 40), 'Сегменты аудитории', font=fb, fill=(20, 20, 30))
    ly = 150
    for name, val, col in parts:
        d.rectangle([560, ly, 590, ly+30], fill=col)
        d.text((600, ly+2), f'{name} - {val}%', font=f, fill=(20, 20, 30))
        ly += 60
    img.save(path)

CHART = '/tmp/_an_audience.png'
make_audience_chart(CHART)

