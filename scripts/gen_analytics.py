from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

FONT = 'Times New Roman'
doc = Document()
st = doc.styles['Normal']
st.font.name = FONT; st.font.size = Pt(13)
st.paragraph_format.line_spacing = 1.4
st.paragraph_format.space_after = Pt(4)
for sec in doc.sections:
    sec.left_margin = Cm(2.5); sec.right_margin = Cm(1.5)
    sec.top_margin = Cm(2); sec.bottom_margin = Cm(2)

def san(t):
    return str(t).replace('—', '-').replace('–', '-')

def p(text='', bold=False, size=13, align=None):
    par = doc.add_paragraph()
    if align is not None: par.alignment = align
    r = par.add_run(san(text)); r.bold = bold; r.font.size = Pt(size); r.font.name = FONT
    return par

def h(text, size=15):
    par = p(text, bold=True, size=size); par.paragraph_format.space_before = Pt(14)
    return par

def bullets(items, mark='• '):
    for it in items:
        par = doc.add_paragraph(); par.paragraph_format.left_indent = Cm(0.7)
        r = par.add_run(mark + san(it)); r.font.name = FONT; r.font.size = Pt(13)

def table(headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, hd in enumerate(headers):
        c = t.rows[0].cells[j]; c.text = ''
        r = c.paragraphs[0].add_run(san(hd)); r.bold = True; r.font.name = FONT; r.font.size = Pt(12)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = t.rows[i + 1].cells[j]; c.text = ''
            r = c.paragraphs[0].add_run(san(v)); r.font.name = FONT; r.font.size = Pt(12)
    for row in t.rows:
        from docx.oxml import OxmlElement
        row._tr.get_or_add_trPr().append(OxmlElement('w:cantSplit'))
    p('')

